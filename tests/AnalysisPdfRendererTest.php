<?php

declare(strict_types=1);

namespace Clesson\Silverstripe\DeveloperTools\Tests;

use Clesson\Silverstripe\DeveloperTools\Services\AnalysisPdfRenderer;
use SilverStripe\Dev\SapphireTest;

/**
 * Verifies baseline PDF export generation for analysis snapshots.
 *
 * @package Clesson\Silverstripe\DeveloperTools
 * @subpackage Tests
 */
class AnalysisPdfRendererTest extends SapphireTest
{
    public function testRenderCreatesPdfDocument(): void
    {
        $pdf = AnalysisPdfRenderer::create()->render(
            'System health report',
            '<h1>Status</h1><p>Everything looks good.</p>',
            '2026-11-24T11:00:00Z'
        );

        self::assertStringStartsWith('%PDF-1.4', $pdf);
        self::assertStringContainsString('/Type /Catalog', $pdf);
        self::assertStringContainsString('/Type /Page', $pdf);
        self::assertStringContainsString('System health report', $pdf);
        self::assertStringContainsString('Generated by silverstripe-developertools', $pdf);
    }

    public function testRenderWrapsLongLines(): void
    {
        $long = str_repeat('alpha ', 80);
        $pdf = AnalysisPdfRenderer::create()->render('System health report', '<p>' . $long . '</p>');

        self::assertStringStartsWith('%PDF-1.4', $pdf);
        self::assertStringContainsString('Page 1 of', $pdf);
        self::assertStringContainsString('alpha', $pdf);
    }

    public function testRenderReportCreatesStructuredRows(): void
    {
        $pdf = AnalysisPdfRenderer::create()->renderReport('System health report', [
            [
                'id' => 'runtime.default_admin',
                'title' => 'Default admin credentials',
                'status' => 'warning',
                'message' => 'Default admin credentials are configured in live mode.',
                'checked_at' => '2026-11-24T11:30:00Z',
            ],
            [
                'id' => 'runtime.https',
                'title' => 'HTTPS request',
                'status' => 'ok',
                'message' => 'Observed as HTTPS in this request.',
                'checked_at' => '2026-11-24T11:30:00Z',
            ],
            [
                'id' => 'runtime.mode',
                'title' => 'Live mode',
                'status' => 'error',
                'message' => 'Installation is not in live mode.',
                'checked_at' => '2026-11-24T11:30:00Z',
            ],
        ]);

        self::assertStringContainsString('Summary: ERROR 1 | WARNING 1 | UNKNOWN 0 | OK 1', $pdf);
        self::assertStringContainsString('Risk points: 7/15 (health 53%)', $pdf);
        self::assertStringContainsString('Legend: ERROR=5, WARNING=2, UNKNOWN=1, OK=0', $pdf);
        self::assertStringContainsString('Top risks (ERROR/WARNING):', $pdf);
        self::assertStringContainsString('[ERROR] Live mode', $pdf);
        self::assertStringContainsString('[WARNING] Default admin credentials', $pdf);
        self::assertStringContainsString('Status', $pdf);
        self::assertStringContainsString('HTTPS request', $pdf);
        self::assertStringContainsString('Default admin credentials', $pdf);
        self::assertStringContainsString('Live mode', $pdf);
        self::assertLessThan(
            strpos($pdf, 'Default admin credentials'),
            strpos($pdf, 'Live mode')
        );
        self::assertLessThan(
            strpos($pdf, 'HTTPS request'),
            strpos($pdf, 'Default admin credentials')
        );
    }

    public function testRenderReportShowsNoRiskHintWhenOnlyOk(): void
    {
        $pdf = AnalysisPdfRenderer::create()->renderReport('System health report', [[
            'id' => 'runtime.https',
            'title' => 'HTTPS request',
            'status' => 'ok',
            'message' => 'Observed as HTTPS in this request.',
            'checked_at' => '2026-11-24T11:30:00Z',
        ]]);

        self::assertStringContainsString('Top risks (ERROR/WARNING):', $pdf);
        self::assertStringContainsString('Risk points: 0/5 (health 100%)', $pdf);
        self::assertStringContainsString('Legend: ERROR=5, WARNING=2, UNKNOWN=1, OK=0', $pdf);
        self::assertStringContainsString('- None', $pdf);
    }
}







